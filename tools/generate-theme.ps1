		'glass-dark'  = @('#eef1fb', '#4f7bff', '#4f7bff')
	}
	# Raised controls, and the text on ink.
	'paper'    = @{
		'paper-light' = @('#f2eee2', '#f2eee2', '#f2eee2')
		'paper-dark'  = @('#1f1e33', '#1f1e33', '#1f1e33')
		'glass-light' = @('#ffffff', 'rgba( 255, 255, 255, 0.55 )', 'rgba( 255, 255, 255, 0.7 )')
		'glass-dark'  = @('#ffffff', 'rgba( 255, 255, 255, 0.08 )', 'rgba( 255, 255, 255, 0.16 )')
	}
	# Windows' own look, menus.
	'surface'  = @{
		'paper-light' = @('#dcd6c4', '#dcd6c4', '#dcd6c4')
		'paper-dark'  = @('#2d2b45', '#2d2b45', '#2d2b45')
		'glass-light' = @('#1d2233', 'rgba( 244, 247, 255, 0.7 )', 'rgba( 255, 255, 255, 0.6 )')
		'glass-dark'  = @('#eef1fb', 'rgba( 28, 31, 50, 0.7 )', 'rgba( 255, 255, 255, 0.14 )')
	}
	# Side panels, wells.
	'surface2' = @{
		'paper-light' = @('#c9c3b0', '#c9c3b0', '#c9c3b0')
		'paper-dark'  = @('#25233b', '#25233b', '#25233b')
		'glass-light' = @('#1d2233', 'rgba( 228, 233, 249, 0.45 )', 'rgba( 120, 132, 180, 0.3 )')
		'glass-dark'  = @('#eef1fb', 'rgba( 12, 14, 28, 0.35 )', 'rgba( 255, 255, 255, 0.1 )')
	}
	'sand'     = @{
		'paper-light' = @('#b8b19c', '#b8b19c', '#b8b19c')
		'paper-dark'  = @('#3a3857', '#3a3857', '#3a3857')
