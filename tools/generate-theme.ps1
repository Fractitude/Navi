# Writes the palettes in Code/Navi/Themes/: _paper-light.scss, _paper-dark.scss, _glass-light.scss, _glass-dark.scss.
#
#   pwsh tools/generate-theme.ps1
#
# How a Navi style sheet is themed. The engine's SCSS has variables and mixins, but no CSS variables, no `&` after the
# selector (`.dark &` doesn't work) and no @each, @if or maps. So a sheet is written once, as a mixin whose colors are
# palette variables, and included once per look under that look's root classes (NaviThemeClasses). Each palette file
# sets the variables when it is imported, and a sheet imports them one after the other:
#
#   @import "../../Themes/_paper-light.scss";
#   @mixin settings-style { Settings { color: $ink-t; .sidebar { background-color: $surface2-bg; } } }
#   @include settings-style;                                // Paper light: what the panel is without a theme class
#   @import "../../Themes/_paper-dark.scss";
#   .theme-paper.scheme-dark { @include settings-style; }
#   @import "../../Themes/_glass-light.scss";
#   .theme-glass.scheme-light { @include settings-style; }
#   @import "../../Themes/_glass-dark.scss";
#   .theme-glass.scheme-dark { @include settings-style; }
#
# Three variables per color (the palette's token), by what the property takes: $<token>-t text, $<token>-bg fills,
# $<token>-bc borders. A token is named for the Paper light color the sheets were first written with.
#
# Change a color below, run this, and commit the files it writes.

$ErrorActionPreference = 'Stop'

# Token => text / bg / border, for each look. Glass fills are see-through: rgba() with the alpha they are drawn at. The
# window, taskbar and menus' own fills (and the Transparency and Blur settings) are the desktop's: NaviDesktop.razor.scss.
