		'glass-dark'  = @('#aab2d0', 'rgba( 70, 76, 112, 0.5 )', 'rgba( 255, 255, 255, 0.18 )')
	}
	# Borders and rules.
	'line'     = @{
		'paper-light' = @('#8a8472', '#8a8472', '#8a8472')
		'paper-dark'  = @('#8b88ad', '#5a5776', '#5a5776')
		'glass-light' = @('#6a7290', 'rgba( 110, 122, 175, 0.3 )', 'rgba( 100, 112, 165, 0.35 )')
		'glass-dark'  = @('#98a0bf', 'rgba( 255, 255, 255, 0.14 )', 'rgba( 255, 255, 255, 0.16 )')
	}
	# Title bars, hovered rows, muted text.
	'mid'      = @{
		'paper-light' = @('#6e6a5c', '#6e6a5c', '#6e6a5c')
		'paper-dark'  = @('#a09dc0', '#9794b8', '#6a678f')
		'glass-light' = @('#5b6280', 'rgba( 82, 98, 160, 0.85 )', 'rgba( 100, 112, 165, 0.35 )')
		'glass-dark'  = @('#a7aec8', 'rgba( 120, 132, 200, 0.5 )', 'rgba( 255, 255, 255, 0.16 )')
	}
	# Hovered and pressed fills, strong borders.
	'deep'     = @{
		'paper-light' = @('#4a4638', '#4a4638', '#4a4638')
		'paper-dark'  = @('#b4b1d2', '#c9c6e6', '#8b88ad')
		'glass-light' = @('#2a3150', '#5b82f7', 'rgba( 70, 84, 140, 0.55 )')
		'glass-dark'  = @('#dfe4f7', '#6a8dff', 'rgba( 255, 255, 255, 0.3 )')
	}
	# Text fields.
	'white'    = @{
		'paper-light' = @('#ffffff', '#ffffff', '#ffffff')
		'paper-dark'  = @('#ffffff', '#1a1930', '#1a1930')
		'glass-light' = @('#ffffff', 'rgba( 255, 255, 255, 0.6 )', 'rgba( 255, 255, 255, 0.7 )')
		'glass-dark'  = @('#ffffff', 'rgba( 255, 255, 255, 0.07 )', 'rgba( 255, 255, 255, 0.14 )')
	}
}

foreach ($look in 'paper-light', 'paper-dark', 'glass-light', 'glass-dark') {
	$sb = New-Object System.Text.StringBuilder
	[void]$sb.Append("// The $look palette. GENERATED by tools/generate-theme.ps1: change the palette there, not here.`r`n")
	[void]$sb.Append("// Importing this sets the color variables for the rules that follow (see the script for how sheets use it).`r`n`r`n")

	foreach ($name in $tokens.Keys) {
		$text, $bg, $bc = $tokens[$name][$look]
		[void]$sb.Append("`$$name-t: $text;`r`n`$$name-bg: $bg;`r`n`$$name-bc: $bc;`r`n")
	}

	$path = Join-Path $PSScriptRoot "..\Code\Navi\Themes\_$look.scss"
	[IO.File]::WriteAllText($path, $sb.ToString())
	"Wrote $path"
}
